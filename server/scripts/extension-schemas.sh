#!/usr/bin/env bash
# Generates the CUE schemas of content extensions from their Go definitions.
#
# Usage (from server/): scripts/extension-schemas.sh generate|check
#
#   generate  regenerate raw definitions and final embedded artifacts in place
#   check     regenerate into a temporary directory and fail if the committed
#             artifacts are stale or missing; never modifies the working tree
#
# Per extension package listed in INPUTS (see docs in server/README.md):
#
#   <pkg>/schema/<name>_go_gen.cue  raw `cue get go` output    (generated)
#   <pkg>/schema/*_patch.cue        companion constraints      (handwritten)
#   <pkg>/schema.cue                self-contained embedded    (generated)
#                                   artifact: raw + companions,
#                                   non-stdlib imports inlined
#
# The cue tool is built from the version pinned in server/go.mod.
set -euo pipefail

# Explicit list of schema inputs: Go packages relative to server/.
INPUTS=(
	pkg/extensions/aiagent
	pkg/extensions/slack
)

MODULE=github.com/infrapad/infrapad/server
HEADER="// Code generated by server/scripts/extension-schemas.sh. DO NOT EDIT."

main() {
	local mode=${1:-}
	case "$mode" in
	generate | check) ;;
	*)
		echo "usage: $0 generate|check" >&2
		exit 2
		;;
	esac

	cd "$(dirname "$0")/.."
	work=$(mktemp -d)
	trap 'rm -rf "$work"' EXIT

	generate_into "$work/out"

	if [ "$mode" = generate ]; then
		for pkg in "${INPUTS[@]}"; do
			mkdir -p "$pkg/schema"
			cp "$work/out/$pkg/schema/"*_go_gen.cue "$pkg/schema/"
			cp "$work/out/$pkg/schema.cue" "$pkg/schema.cue"
		done
		# Remove stale raw files (e.g. after renaming a Go source package).
		for pkg in "${INPUTS[@]}"; do
			for f in "$pkg/schema/"*_go_gen.cue; do
				if [ ! -e "$work/out/$f" ]; then rm -f "$f"; fi
			done
		done
		echo "extension schemas generated"
	else
		check_against "$work/out"
	fi
}

# generate_into writes the generated files of all INPUTS under $1, mirroring
# the server/ layout.
generate_into() {
	local out=$1 ws="$work/ws"
	go build -o "$work/cue" cuelang.org/go/cmd/cue

	# Generate in an isolated CUE module so no generated or companion CUE
	# file is written to (or read back from) the source tree.
	mkdir -p "$ws/cue.mod"
	printf 'module: "infrapad.local/extension-schemas"\nlanguage: version: "v0.17.0"\n' >"$ws/cue.mod/module.cue"
	local gowork
	gowork=$(go env GOWORK)
	if [ -z "$gowork" ] || [ "$gowork" = off ]; then
		gowork="$work/go.work"
		printf 'go %s\nuse %s\n' "$(go list -m -f '{{.GoVersion}}')" "$PWD" >"$gowork"
	fi

	local pkgs=() pkg
	for pkg in "${INPUTS[@]}"; do
		pkgs+=("$MODULE/$pkg")
	done
	(cd "$ws" && GOWORK="$gowork" "$work/cue" get go "${pkgs[@]}")

	local gen="$ws/cue.mod/gen"
	# `cue get go` also copies existing .cue files of the Go package
	# directories (e.g. the embedded schema.cue); keep only Go-derived files.
	find "$gen" -name '*.cue' ! -name '*_go_gen.cue' -delete

	for pkg in "${INPUTS[@]}"; do
		mkdir -p "$out/$pkg/schema"
		cp "$gen/$MODULE/$pkg/"*_go_gen.cue "$out/$pkg/schema/"
		# Companion constraints join the generated package before assembly.
		for f in "$pkg/schema/"*_patch.cue; do
			if [ -e "$f" ]; then cp "$f" "$gen/$MODULE/$pkg/"; fi
		done
	done

	for pkg in "${INPUTS[@]}"; do
		{
			echo "$HEADER"
			echo "// Self-contained schema assembled from schema/*_go_gen.cue and"
			echo "// schema/*_patch.cue; run 'task server:extensions:schema:generate'."
			echo
			(cd "$ws" && "$work/cue" def --inline-imports "$MODULE/$pkg") |
				sed -e '/^\/\/ Code generated by cue get go\. DO NOT EDIT\.$/d' \
					-e '/^\/\/cue:generate /d' |
				cat -s | sed -e '1{/^$/d}'
		} >"$out/$pkg/schema.cue"
	done
}

# check_against compares the generated files under $1 with the committed ones.
check_against() {
	local out=$1 stale=0 pkg f
	for pkg in "${INPUTS[@]}"; do
		for f in "$pkg/schema.cue" $(cd "$out" && ls "$pkg/schema/"*_go_gen.cue); do
			if ! diff -u "$f" "$out/$f" >/dev/null 2>&1; then
				echo "stale or missing: server/$f" >&2
				stale=1
			fi
		done
		for f in "$pkg/schema/"*_go_gen.cue; do
			if [ -e "$f" ] && [ ! -e "$out/$f" ]; then
				echo "unexpected generated file: server/$f" >&2
				stale=1
			fi
		done
	done
	if [ "$stale" -ne 0 ]; then
		echo "extension schemas are out of date; run 'task server:extensions:schema:generate'" >&2
		exit 1
	fi
	echo "extension schemas are up to date"
}

main "$@"
